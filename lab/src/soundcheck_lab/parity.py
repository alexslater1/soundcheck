"""Parity cases: the guard against training/serving skew.

``contracts/ranking/parity-cases.json`` holds weights, a feature vector and the score Python
computes for them. pytest (here) and JUnit (the feed module) both recompute every score and
require ``|Δ| < 1e-6``. The file is generated by ``generate_cases`` with a fixed seed, so
regenerating it without changing the scorer or the schema reproduces it byte for byte.
"""

from __future__ import annotations

import json
import random
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from soundcheck_lab.schema import DEFAULT_SCHEMA_PATH, FeatureSchema, load_schema
from soundcheck_lab.scorer import BIAS, logit, score

DEFAULT_CASES_PATH = DEFAULT_SCHEMA_PATH.with_name("parity-cases.json")
TOLERANCE = 1e-6
SEED = 20261002

# Ranking config v1, the weights the feed starts with.
V1_WEIGHTS: dict[str, float] = {
    "bias": -2.0,
    "follows_author": 1.6,
    "follows_artist": 1.2,
    "artist_affinity": 1.0,
    "author_affinity": 0.8,
    "genre_similarity": 1.0,
    "gig_relation": 1.4,
    "proximity": 0.6,
    "recency": 1.5,
    "engagement_quality": 1.8,
    "social_proof": 0.7,
    "seen": -2.5,
    "position_prior": 0.0,
}


@dataclass(frozen=True, slots=True)
class Case:
    name: str
    weights: dict[str, float]
    features: list[float]
    expected_logit: float
    expected_score: float


@dataclass(frozen=True, slots=True)
class Mismatch:
    name: str
    expected: float
    actual: float


def generate_cases(schema: FeatureSchema, seed: int = SEED) -> list[Case]:
    """Hand-picked corner cases with the v1 weights, then seeded random weights and features."""
    rng = random.Random(seed)
    n = len(schema)
    cases: list[tuple[str, dict[str, float], list[float]]] = [
        ("v1 weights, nothing known about the post", V1_WEIGHTS, [0.0] * n),
        ("v1 weights, every feature at its maximum", V1_WEIGHTS, [1.0] * n),
    ]
    for feature in schema.features:
        one_hot = [0.0] * n
        one_hot[feature.index] = 1.0
        cases.append((f"v1 weights, only {feature.name}", V1_WEIGHTS, one_hot))
    extreme = {name: 10.0 for name in (BIAS, *schema.names)}
    cases.append(("largest allowed weights, all features on", extreme, [1.0] * n))
    cases.append(
        ("smallest allowed weights, all features on", {k: -10.0 for k in extreme}, [1.0] * n)
    )
    for i in range(10):
        weights = {name: round(rng.uniform(-10.0, 10.0), 4) for name in (BIAS, *schema.names)}
        features = [round(rng.random(), 6) for _ in range(n)]
        cases.append((f"random {i + 1}", weights, features))
    return [
        Case(
            name,
            dict(weights),
            features,
            logit(weights, features, schema),
            score(weights, features, schema),
        )
        for name, weights, features in cases
    ]


def to_document(schema: FeatureSchema, cases: list[Case]) -> dict[str, Any]:
    return {
        "schemaVersion": schema.version,
        "description": (
            "Scores computed by soundcheck_lab.scorer for the Java parity test"
            ". Regenerate with `uv run soundcheck-lab parity --write` after "
            "changing the feature schema or the scorer."
        ),
        "tolerance": TOLERANCE,
        "cases": [
            {
                "name": case.name,
                "weights": case.weights,
                "features": case.features,
                "expectedLogit": case.expected_logit,
                "expectedScore": case.expected_score,
            }
            for case in cases
        ],
    }


def render(schema: FeatureSchema) -> str:
    """The file's exact contents (floats via ``repr``, so they round-trip to the same doubles)."""
    return json.dumps(to_document(schema, generate_cases(schema)), indent=2) + "\n"


def load_cases(path: Path = DEFAULT_CASES_PATH) -> tuple[int, list[Case]]:
    raw = json.loads(path.read_text(encoding="utf-8"))
    cases = [
        Case(
            name=str(c["name"]),
            weights={str(k): float(v) for k, v in c["weights"].items()},
            features=[float(f) for f in c["features"]],
            expected_logit=float(c["expectedLogit"]),
            expected_score=float(c["expectedScore"]),
        )
        for c in raw["cases"]
    ]
    return int(raw["schemaVersion"]), cases


def check(path: Path = DEFAULT_CASES_PATH, schema: FeatureSchema | None = None) -> list[Mismatch]:
    """Recomputes every case; returns the ones that differ by ``TOLERANCE`` or more."""
    schema = schema or load_schema()
    version, cases = load_cases(path)
    if version != schema.version:
        raise ValueError(
            f"parity cases are for schema v{version}, the schema is v{schema.version}: regenerate"
        )
    mismatches = []
    for case in cases:
        actual = score(case.weights, case.features, schema)
        if abs(actual - case.expected_score) >= TOLERANCE:
            mismatches.append(Mismatch(case.name, case.expected_score, actual))
            continue
        # A score near 0 or 1 hardly moves with the logit; the logit itself is compared as well.
        actual_logit = logit(case.weights, case.features, schema)
        if abs(actual_logit - case.expected_logit) >= TOLERANCE:
            mismatches.append(Mismatch(case.name + " (logit)", case.expected_logit, actual_logit))
    return mismatches
