"""Engagement bootstrap: a scripted pass so post stats, affinities and feeds have signal.

SYNTHETIC: every event here is generated by this script for a seeded persona, not by a person. It
is simpler than the simulator, which models tastes properly. Each persona opens For
You a few times and, like the app (`watchTracker.ts`, `LikeButton.tsx`), sends IMPRESSION,
VIEW_START, WATCH_PROGRESS (25/50/75 %), COMPLETE and LIKE events; a like is also given through PUT
/posts/{id}/like. How far a persona watches depends on how well the post matches their genres and
whether they went to that gig."""

from __future__ import annotations

import os
from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass
from datetime import UTC, datetime
from typing import Any
from urllib.parse import urlparse

from soundcheck_lab import events as ev
from soundcheck_lab.seed.api import Api
from soundcheck_lab.seed.personas import Persona
from soundcheck_lab.seed.run import stable

Log = Callable[[str], None]


def interest(persona: Persona, post: dict[str, Any]) -> float:
    """0..1: the share of the post's artist genres the persona likes, plus 0.3 if they went to that
    gig."""
    genres = {g for artist in post.get("artists", []) for g in artist.get("genres", [])}
    score = len(genres & set(persona.genres)) / len(genres) if genres else 0.2
    gig = post.get("gig") or {}
    if gig.get("myAttendance") == "WENT":
        score += 0.3
    return min(1.0, score)


def reactions(
    persona: Persona, post: dict[str, Any], position: int, session: str, salt: str
) -> tuple[list[dict[str, Any]], bool]:
    """The events one persona sends for one feed item, and whether they like it. Deterministic."""
    level = interest(persona, post)
    roll = (stable(persona.handle + post["id"] + salt) % 1000) / 1000
    now = datetime.now(UTC).isoformat()

    def event(kind: str, value: float | None = None) -> dict[str, Any]:
        return ev.event(post["id"], kind, position, session, now, value)

    events = [event("IMPRESSION")]
    if roll < 0.35 + 0.5 * level:
        events += [event("VIEW_START"), event("WATCH_PROGRESS", 0.25), event("WATCH_PROGRESS", 0.5)]
        if roll < 0.15 + 0.6 * level:
            events += [event("WATCH_PROGRESS", 0.75), event("COMPLETE")]
    like = roll < 0.05 + 0.35 * level and not post.get("likedByMe")
    if like:
        events.append(event("LIKE"))
    return events, like


def engage(api: Api, people: Sequence[Persona], log: Log, sessions: int = 2, pages: int = 3) -> int:
    sent = 0
    for persona in people:
        for s in range(sessions):
            cursor: str | None = None
            for _ in range(pages):
                feed = api.get(persona, "/api/v1/feed/home", cursor=cursor, limit=10)
                batch: list[dict[str, Any]] = []
                for item in feed["items"]:
                    events, like = reactions(
                        persona, item["post"], item["position"], feed["sessionId"], str(s)
                    )
                    if like:
                        api.put(persona, f"/api/v1/posts/{item['post']['id']}/like")
                    batch += events
                sent += ev.send(api, persona, batch)
                cursor = feed.get("nextCursor")
                if not cursor:
                    break
    log(f"engagement (synthetic): {sent} events from {len(people)} personas")
    return sent


@dataclass(frozen=True)
class Report:
    feed_sizes: dict[str, int]
    posts: int | None  # None: the database wasn't reachable (a remote API)
    posts_with_stats: int | None

    @property
    def stats_share(self) -> float | None:
        if self.posts is None or self.posts_with_stats is None:
            return None
        return self.posts_with_stats / self.posts if self.posts else 0.0


def feed_size(api: Api, persona: Persona, want: int = 30) -> int:
    """How many For You items the persona can scroll through (stops counting at {@code want})."""
    seen, cursor = 0, None
    while seen < want:
        page = api.get(persona, "/api/v1/feed/home", cursor=cursor, limit=10)
        seen += len(page["items"])
        cursor = page.get("nextCursor")
        if not cursor or not page["items"]:
            break
    return seen


def post_stats_share() -> tuple[int, int]:
    """(published posts, of which have any engagement in post_stats), read from the database."""
    import psycopg

    env = os.environ.get
    with (
        psycopg.connect(
            host=env("DB_HOST", "localhost"),
            port=env("DB_PORT", "5432"),
            dbname=env("DB_NAME", "soundcheck"),
            user=env("DB_USER", "soundcheck"),
            password=env("DB_PASSWORD", "soundcheck"),
        ) as conn,
        conn.cursor() as cur,
    ):
        cur.execute("""
            select count(*),
                   count(*) filter (where s.impressions + s.views + s.completes + s.likes > 0)
            from content.post p left join signals.post_stats s on s.post_id = p.id
            where p.status = 'PUBLISHED'
        """)
        row = cur.fetchone()
    return (int(row[0]), int(row[1])) if row else (0, 0)


LOCAL_HOSTS = frozenset({"localhost", "127.0.0.1", "::1"})


def database_reachable(api_url: str, environ: Mapping[str, str] = os.environ) -> bool:
    """The post_stats figure is read from the database itself: there on the local stack, or
    wherever DB_HOST points. A remote API's database (on AWS, in a private subnet) is not."""
    host = urlparse(api_url).hostname or ""
    return bool(environ.get("DB_HOST")) or host in LOCAL_HOSTS


def report(
    api: Api,
    people: Sequence[Persona],
    log: Log,
    api_url: str = "http://localhost:8088",
    stats: Callable[[], tuple[int, int]] = post_stats_share,
    environ: Mapping[str, str] = os.environ,
) -> Report:
    sizes = {p.handle: feed_size(api, p) for p in people}
    short = [h for h, n in sizes.items() if n < 30]
    log(
        f"For You: {sum(n >= 30 for n in sizes.values())}/{len(sizes)} personas have ≥ 30 items"
        + (f" (short: {', '.join(f'{h} {sizes[h]}' for h in short)})" if short else "")
    )
    if not database_reachable(api_url, environ):
        log("post_stats: n/a (remote)")
        return Report(sizes, None, None)
    posts, with_stats = stats()
    log(
        f"post_stats: {with_stats}/{posts} published posts have engagement "
        f"({100 * with_stats / posts if posts else 0:.0f} %; the target is ≥ 70 %)"
    )
    return Report(sizes, posts, with_stats)
