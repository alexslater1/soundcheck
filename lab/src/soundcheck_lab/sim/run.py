"""`soundcheck-lab simulate`: synthetic personas use the real API in rounds.

SYNTHETIC: every account and event this makes is generated by a click model, not by a person.

A run:
1. reads the world (sim/world.py) and draws the personas (sim/personas.py);
2. sets each persona up through the API: signs it in (registering on the first run), sets its home
   town, follows some favourite acts and authors, marks 0–3 gigs;
3. runs `days` rounds in real time. In each round the personas with a session in it open For You
   (`GET /feed/home`, one page at a time, never more items than they will look at, so everything
   served is seen), react to each item through the click model, like and hide through the API as
   the app does, and send their events (`POST /events`, at most 100 a request). Between rounds it
   waits one rollup interval plus 2 s, so the next round's feeds are ranked on the earlier rounds;
4. writes `lab/data/sim-<seed>-<ts>.json`: the parameters, the personas' hidden tastes, each
   session's round and feed session ids (the lab's time split is "the last 20 % of rounds"), counts
   and timings.

Same seed on the same starting database → the same personas, tastes and choices. The feed itself
depends on server state (and on when the rollups ran), so a run is deterministic only given the
same starting database, and the item-by-item outcome only given the same served items."""

from __future__ import annotations

import json
import time
from collections.abc import Callable, Iterable, Iterator, Sequence
from concurrent.futures import ThreadPoolExecutor
from dataclasses import asdict, dataclass, field
from datetime import UTC, datetime
from pathlib import Path
from typing import Any, Protocol

from soundcheck_lab import events as ev
from soundcheck_lab.seed.personas import Persona
from soundcheck_lab.sim import click
from soundcheck_lab.sim.personas import SimPersona, rng_for
from soundcheck_lab.sim.world import World

HONESTY = "synthetic personas; engagement is generated by a click model"
PAGE = 10  # items per GET /feed/home, as the app asks
Log = Callable[[str], None]


class Client(Protocol):
    """What the simulator needs from `seed.api.Api`."""

    ids: dict[str, str]

    def sign_in(self, persona: Persona) -> str: ...

    def get(self, persona: Persona, url: str, **params: Any) -> Any: ...

    def post(self, persona: Persona, url: str, body: Any = None) -> Any: ...

    def put(self, persona: Persona, url: str, body: Any = None) -> Any: ...

    def patch(self, persona: Persona, url: str, body: Any = None) -> Any: ...


class WorldMismatchError(Exception):
    """The API served a post the world (from --db) doesn't have: --db is not the API's database."""


@dataclass(frozen=True)
class Settings:
    personas: int
    sessions: int
    days: int
    seed: int
    api_url: str
    round_wait_s: float = 12.0  # one rollup interval (10 s on the simulator's stack) plus 2 s
    workers: int = 4
    params: click.Params = field(default_factory=click.Params)


@dataclass
class SessionLog:
    persona: int
    user_id: str
    round: int
    index: int  # the persona's n-th session
    feed_sessions: list[str] = field(
        default_factory=list
    )  # usually one; a new one if a page runs dry
    served: int = 0
    engaged: int = 0  # by the click model (the label view's `positive` is computed from the events)
    events: int = 0
    likes: int = 0
    hides: int = 0
    profile_taps: int = 0
    gig_taps: int = 0
    seconds: float = 0.0


@dataclass
class Result:
    started_at: str
    settings: Settings
    personas: list[SimPersona]
    user_ids: dict[int, str]
    setup_s: float = 0.0
    round_s: list[float] = field(default_factory=list)
    sessions: list[SessionLog] = field(default_factory=list)
    total_s: float = 0.0
    check: dict[str, Any] | None = None

    def counts(self) -> dict[str, int]:
        keys = ("served", "engaged", "events", "likes", "hides", "profile_taps", "gig_taps")
        totals = {k: sum(int(getattr(s, k)) for s in self.sessions) for k in keys}
        return {"personas": len(self.personas), "sessions": len(self.sessions), **totals}


def setup(api: Client, world: World, persona: SimPersona) -> str:
    """Signs the persona in and makes its starting choices (all idempotent, so a rerun with the same
    seed changes nothing). Returns its user id."""
    account = persona.account
    api.sign_in(account)
    if persona.city is not None and persona.city in world.city_ids:
        api.patch(account, "/api/v1/me", {"homeCityId": world.city_ids[persona.city]})
    for artist_id in persona.follow_artists:
        api.put(account, f"/api/v1/artists/{artist_id}/follow")
    for author_id in sorted(persona.taste.followed_authors):
        api.put(account, f"/api/v1/users/{author_id}/follow")
    for mark in persona.attend:
        api.put(account, f"/api/v1/gigs/{mark.gig_id}/attendance", {"status": mark.status})
    return api.ids[account.handle]


def session(
    api: Client,
    world: World,
    persona: SimPersona,
    user_id: str,
    round_: int,
    index: int,
    params: click.Params,
    now: Callable[[], str] = lambda: datetime.now(UTC).isoformat(),
) -> SessionLog:
    """One session: the persona scrolls For You until it has seen `session_length` items (or the
    feed ends), reacting to each through the click model, then sends its events."""
    started = time.monotonic()
    rng = rng_for(persona.seed, persona.n, 1, index)
    account = persona.account
    log = SessionLog(persona.n, user_id, round_, index)
    events: list[ev.Event] = []
    cursor: str | None = None
    while log.served < persona.session_length:
        want = min(PAGE, persona.session_length - log.served)
        page = api.get(account, "/api/v1/feed/home", cursor=cursor, limit=want)
        feed_session = str(page["sessionId"])
        if feed_session not in log.feed_sessions:
            log.feed_sessions.append(feed_session)
        for item in page["items"]:
            post = item["post"]
            post_id = str(post["id"])
            if post_id not in world.posts:
                raise WorldMismatchError(
                    f"the API served post {post_id}, which --db doesn't have: point --db at the "
                    "database behind --api"
                )
            position = int(item["position"])
            reaction = click.react(
                rng,
                persona.taste,
                world.item(post_id),
                position,
                social=persona.social,
                liked_before=bool(post.get("likedByMe")),
                params=params,
            )
            if reaction.like:  # the app's LikeButton: PUT the like, then track it
                api.put(account, f"/api/v1/posts/{post_id}/like")
            if reaction.hide:  # PostActions: "Show me less", then track it
                api.post(account, f"/api/v1/posts/{post_id}/hide")
            stamp = now()
            events += [
                ev.event(post_id, kind, position, feed_session, stamp, value)
                for kind, value in click.event_kinds(reaction)
            ]
            log.served += 1
            log.engaged += reaction.engaged
            log.likes += reaction.like
            log.hides += reaction.hide
            log.profile_taps += reaction.profile_tap
            log.gig_taps += reaction.gig_tap
        cursor = page.get("nextCursor")
        if not cursor or not page["items"]:
            break
    log.events = ev.send(api, account, events)
    log.seconds = round(time.monotonic() - started, 3)
    return log


def _parallel[T, R](workers: int, fn: Callable[[T], R], jobs: Iterable[T]) -> Iterator[R]:
    if workers <= 1:
        yield from map(fn, jobs)
        return
    with ThreadPoolExecutor(max_workers=workers) as pool:
        yield from pool.map(fn, jobs)


def run(
    settings: Settings,
    api: Client,
    world: World,
    personas: Sequence[SimPersona],
    log: Log,
    sleep: Callable[[float], None] = time.sleep,
) -> Result:
    started = time.monotonic()
    result = Result(datetime.now(UTC).isoformat(), settings, list(personas), {})
    log(f"SYNTHETIC: {HONESTY}")
    log(
        f"simulate: {len(personas)} personas × {settings.sessions} sessions over {settings.days} "
        f"rounds against {settings.api_url} (seed {settings.seed}; world: {len(world.posts)} posts)"
    )

    # Sign-ins are paced inside the client under the per-IP auth limit (0.5 s apart locally), which
    # bounds set-up at ~100 s for 200 personas; running it on threads was measured to save nothing.
    for persona in personas:
        result.user_ids[persona.n] = setup(api, world, persona)
    result.setup_s = round(time.monotonic() - started, 1)
    log(f"set-up: {len(personas)} personas signed in and following in {result.setup_s} s")

    for round_ in range(settings.days):
        began = time.monotonic()
        jobs = [
            (p, i) for p in personas for i, r in enumerate(p.rounds) if r == round_
        ]  # persona order, then session order

        def one(job: tuple[SimPersona, int], round_: int = round_) -> SessionLog:
            persona, index = job
            return session(
                api, world, persona, result.user_ids[persona.n], round_, index, settings.params
            )

        done = list(_parallel(settings.workers, one, jobs))
        result.sessions += done
        result.round_s.append(round(time.monotonic() - began, 1))
        log(
            f"round {round_ + 1}/{settings.days}: {len(done)} sessions, "
            f"{sum(s.served for s in done)} served, {sum(s.engaged for s in done)} engaged "
            f"in {result.round_s[-1]} s"
        )
        if round_ < settings.days - 1:
            sleep(settings.round_wait_s)
    result.total_s = round(time.monotonic() - started, 1)
    counts = result.counts()
    log(
        f"done in {result.total_s} s: {counts['sessions']} sessions, {counts['served']} served, "
        f"{counts['engaged']} engaged, {counts['events']} events, {counts['likes']} likes "
        f"(SYNTHETIC: {HONESTY})"
    )
    return result


def _persona_json(p: SimPersona, user_id: str | None) -> dict[str, Any]:
    return {
        "n": p.n,
        "handle": p.handle,
        "userId": user_id,
        "city": p.city,
        "social": round(p.social, 4),
        "sessionLength": p.session_length,
        "rounds": list(p.rounds),
        "genres": {g: round(w, 4) for g, w in sorted(p.taste.genres.items())},
        "favouriteArtists": sorted(p.taste.favourite_artists),
        "followedArtists": list(p.follow_artists),
        "followedAuthors": sorted(p.taste.followed_authors),
        "attended": [asdict(a) for a in p.attend],
    }


def to_json(result: Result, sha: str | None = None) -> dict[str, Any]:
    s = result.settings
    return {
        "synthetic": True,
        "note": f"SYNTHETIC: {HONESTY}",
        "startedAt": result.started_at,
        "commit": sha,
        "parameters": {
            "personas": s.personas,
            "sessions": s.sessions,
            "rounds": s.days,
            "seed": s.seed,
            "api": s.api_url,
            "roundWaitS": s.round_wait_s,
            "workers": s.workers,
            "clickModel": asdict(s.params),
        },
        "counts": result.counts(),
        "timings": {
            "setupS": result.setup_s,
            "roundS": result.round_s,
            "totalS": result.total_s,
        },
        "check": result.check,
        "personas": [_persona_json(p, result.user_ids.get(p.n)) for p in result.personas],
        "sessions": [
            {
                "persona": x.persona,
                "userId": x.user_id,
                "round": x.round,
                "index": x.index,
                "feedSessions": x.feed_sessions,
                "served": x.served,
                "engaged": x.engaged,
                "events": x.events,
                "likes": x.likes,
                "hides": x.hides,
                "seconds": x.seconds,
            }
            for x in result.sessions
        ],
    }


def write(result: Result, out_dir: Path, sha: str | None = None) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now(UTC).strftime("%Y%m%dT%H%M%SZ")
    path = out_dir / f"sim-{result.settings.seed}-{stamp}.json"
    path.write_text(json.dumps(to_json(result, sha), indent=1) + "\n", encoding="utf-8")
    return path
